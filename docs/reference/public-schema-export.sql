CREATE TABLE public.access_grants (
  id uuid NOT NULL DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL,
  source text NOT NULL CHECK (source = ANY (ARRAY['invite'::text, 'manual'::text, 'payment'::text, 'admin'::text])),
  invite_code_id uuid,
  plan text NOT NULL CHECK (plan = ANY (ARRAY['premium'::text, 'full_premium'::text])),
  status text NOT NULL DEFAULT 'pending'::text CHECK (status = ANY (ARRAY['active'::text, 'expired'::text, 'revoked'::text, 'pending'::text])),
  starts_at timestamp with time zone NOT NULL DEFAULT now(),
  expires_at timestamp with time zone,
  revoked_at timestamp with time zone,
  revoked_by uuid,
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  updated_at timestamp with time zone NOT NULL DEFAULT now(),
  CONSTRAINT access_grants_pkey PRIMARY KEY (id),
  CONSTRAINT access_grants_invite_code_id_fkey FOREIGN KEY (invite_code_id) REFERENCES public.invite_codes(id)
);
