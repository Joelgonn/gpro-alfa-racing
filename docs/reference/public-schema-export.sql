CREATE TABLE public.energy_observations (
  id bigint GENERATED ALWAYS AS IDENTITY NOT NULL,
  created_at timestamp with time zone DEFAULT now(),
  track_name text NOT NULL,
  track_factor numeric NOT NULL,
  energia_inicial numeric NOT NULL CHECK (energia_inicial >= 0::numeric AND energia_inicial <= 100::numeric),
  energia_final numeric NOT NULL CHECK (energia_final >= 0::numeric AND energia_final <= 100::numeric),
  perda_energia numeric NOT NULL,
  xp integer NOT NULL CHECK (xp IS NULL OR xp >= 0 AND xp <= 300),
  stamina integer NOT NULL CHECK (stamina IS NULL OR stamina >= 0 AND stamina <= 250),
  idade integer NOT NULL CHECK (idade IS NULL OR idade >= 0 AND idade <= 50),
  peso integer NOT NULL CHECK (peso IS NULL OR peso >= 0 AND peso <= 100),
  ctr integer NOT NULL CHECK (ctr IS NULL OR ctr >= 0 AND ctr <= 100),
  user_id uuid,
  chassis integer CHECK (chassis IS NULL OR chassis >= 0 AND chassis <= 9),
  engine integer CHECK (engine IS NULL OR engine >= 0 AND engine <= 9),
  front_wing integer CHECK (front_wing IS NULL OR front_wing >= 0 AND front_wing <= 9),
  rear_wing integer CHECK (rear_wing IS NULL OR rear_wing >= 0 AND rear_wing <= 9),
  underbody integer CHECK (underbody IS NULL OR underbody >= 0 AND underbody <= 9),
  sidepods integer CHECK (sidepods IS NULL OR sidepods >= 0 AND sidepods <= 9),
  cooling integer CHECK (cooling IS NULL OR cooling >= 0 AND cooling <= 9),
  gearbox integer CHECK (gearbox IS NULL OR gearbox >= 0 AND gearbox <= 9),
  brakes integer CHECK (brakes IS NULL OR brakes >= 0 AND brakes <= 9),
  suspension integer CHECK (suspension IS NULL OR suspension >= 0 AND suspension <= 9),
  electronics integer CHECK (electronics IS NULL OR electronics >= 0 AND electronics <= 9),
  race_completed boolean DEFAULT false,
  source character varying,
  race_clean boolean DEFAULT false,
  weather character varying DEFAULT 'Seca'::character varying,
  final_position integer,
  reliability integer DEFAULT 5 CHECK (reliability >= 1 AND reliability <= 5),
  temporada character varying,
  corrida character varying,
  voltas integer,
  corners integer,
  weather_condition character varying DEFAULT 'SECA'::character varying CHECK (weather_condition::text = ANY (ARRAY['SECA'::character varying, 'MOLHADA'::character varying, 'MISTA'::character varying]::text[])),
  validation_status character varying DEFAULT 'VALIDA'::character varying CHECK (validation_status::text = ANY (ARRAY['VALIDA'::character varying, 'SUSPEITA'::character varying, 'DESCARTADA'::character varying]::text[])),
  observacoes text,
  CONSTRAINT energy_observations_pkey PRIMARY KEY (id)
);
